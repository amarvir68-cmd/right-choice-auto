-- Customer lead tables remain protected by RLS. Anonymous/public users may no longer write directly.
alter table public.vehicle_inquiries enable row level security;
alter table public.repair_requests enable row level security;

drop policy if exists "public submit vehicle inquiries" on public.vehicle_inquiries;
drop policy if exists "public submit repair requests" on public.repair_requests;

revoke insert, update, delete, truncate, references, trigger on public.vehicle_inquiries from anon;
revoke insert, update, delete, truncate, references, trigger on public.repair_requests from anon;
revoke select on public.vehicle_inquiries from anon;
revoke select on public.repair_requests from anon;

-- Authenticated users still require the admin RLS policy to read/manage leads.
revoke all on public.vehicle_inquiries from authenticated;
revoke all on public.repair_requests from authenticated;
grant select,insert,update,delete on public.vehicle_inquiries to authenticated;
grant select,insert,update,delete on public.repair_requests to authenticated;

-- Security audit trail. Do not store customer message bodies or passwords here.
create table if not exists public.admin_audit_logs (
  id bigint generated by default as identity primary key,
  admin_user_id uuid not null default auth.uid(),
  action text not null check(length(action) between 2 and 80),
  entity_type text not null check(length(entity_type) between 2 and 80),
  entity_id text,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);
alter table public.admin_audit_logs enable row level security;
revoke all on public.admin_audit_logs from public, anon;
grant select,insert on public.admin_audit_logs to authenticated;
drop policy if exists "admins read audit logs" on public.admin_audit_logs;
create policy "admins read audit logs" on public.admin_audit_logs for select to authenticated using(public.is_admin());
drop policy if exists "admins write audit logs" on public.admin_audit_logs;
create policy "admins write audit logs" on public.admin_audit_logs for insert to authenticated with check(public.is_admin() and admin_user_id=auth.uid());
create index if not exists admin_audit_logs_created_at_idx on public.admin_audit_logs(created_at desc);


-- Analytics writes also go through the server endpoint to reduce direct database abuse.
drop policy if exists "public insert anonymous analytics" on public.analytics_events;
revoke insert on public.analytics_events from anon;
